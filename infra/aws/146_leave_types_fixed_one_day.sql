-- 146: 휴가 종류 카탈로그 교정 — 1일만 부여되는 휴가에 days=1 설정(2026-08-10 사용자 규정 확인).
-- 사용자 확정 규정: 종료일을 직접 지정하는 휴가는 연차·반차·병가·공가(예비군)뿐이고,
-- 나머지는 경조 규정대로 자동 부여되거나 1일만 부여된다.
-- 공가(민방위)·검진(임신기)가 days=NULL(실사용 기간만큼)로 남아 있어 기안 폼의 자동 부여가
-- 동작하지 않았다(사용자가 종료일을 직접 골라야 했다). 공가(건강검진)은 이미 1로 맞음.
-- days 는 관리자 화면에서 편집 가능한 값이라 여기서는 "아직 NULL 인 경우"만 채운다(멱등·수동 편집 존중).

UPDATE leave_types
   SET days = 1
 WHERE key IN ('official_civil', 'exam_fetus')
   AND days IS NULL;
