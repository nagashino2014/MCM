-- 303: 개인카드 지출결의서 양식 이름을 '지출결의서(개인)'으로 변경(G-8, 2026-10-20 사용자 결정).
--
-- 배경: 지출 행은 증빙 불러오기로만 만든다(직접 입력 불허). 이 양식은 모바일로 찍은 개인카드 영수증뿐 아니라
--   웹에서 등록하는 '기타 개인 지출증빙'(계좌이체 확인증·수기 영수증 등)도 담으므로 '개인카드'가 범위를 좁게 보이게 한다.
-- 범위: approval_forms 의 name·description 만 바꾼다. 필드 정의(fields)·버전은 그대로라 버전 스냅샷을 만들지 않는다.
--   이미 만든 문서의 제목(approval_docs.title)은 바꾸지 않는다.
-- 멱등: 예전 이름일 때만 바꾼다(관리 화면에서 이미 다른 이름으로 고쳤으면 건드리지 않는다).

UPDATE approval_forms
   SET name = '지출결의서(개인)',
       description = '개인 경비 결의 — 모바일 촬영 영수증·기타 개인 지출증빙 연동, 월 1회 일괄 경비 정산(CMS) 대상',
       updated_at = now()::text
 WHERE form_id = 'frm-expense-personal'
   AND name = '지출 결의서(개인카드)';
